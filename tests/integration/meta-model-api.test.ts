// Real SAM 3.1 output for public/example-room/before.jpg with the phrase
// "pillow" (October 31, 2026): two pillows on the sofa.
const fixture = () =>
  readFile(new URL('../fixtures/sam/before-pillow.txt', import.meta.url), 'utf8');

test('SAM output becomes outlines in source pixels with a visual share', async () => {
  const parsed = await parseSegmentation('pillow', await fixture());
  assert.equal(parsed.width, 1600);
  assert.equal(parsed.height, 1000);
  assert.equal(parsed.segments.length, 2);
  for (const segment of parsed.segments) {
    assert.ok(segment.confidence! > 0.9);
    assert.match(segment.path, /^M[\d.]+ /);
    // Both pillows sit on the sofa, right of centre.
    assert.ok(segment.box.left > 900 && segment.box.right < 1200);
    assert.ok(segment.box.top > 500 && segment.box.bottom < 700);
    // A mask covers part of its box, and the box is a small part of the photo.
    const boxShare =
      ((segment.box.right - segment.box.left) * (segment.box.bottom - segment.box.top)) /
      (1600 * 1000);
    assert.ok(segment.imageShare > 0 && segment.imageShare < boxShare);
  }
  assert.deepEqual((await parseSegmentation('unicorn', '')).segments, []);
});

const key = 'synthetic-meta-key-for-tests-only';
async function withFetch(
  reply: (url: string, body: Record<string, unknown>) => { status?: number; json: unknown },
  run: (calls: { url: string; body: Record<string, unknown>; auth: string }[]) => Promise<void>,
) {
  const previousFetch = globalThis.fetch,
    previousKey = process.env.MUSE_API_KEY;
  const calls: { url: string; body: Record<string, unknown>; auth: string }[] = [];
  process.env.MUSE_API_KEY = key;
  globalThis.fetch = (async (url: string, init: RequestInit) => {
    const body = JSON.parse(String(init.body));
    calls.push({ url, body, auth: (init.headers as Record<string, string>).Authorization! });
    const { status = 200, json } = reply(url, body);
    return new Response(JSON.stringify(json), { status });
  }) as typeof fetch;
  try {
    await run(calls);
  } finally {
    globalThis.fetch = previousFetch;
    if (previousKey === undefined) delete process.env.MUSE_API_KEY;
    else process.env.MUSE_API_KEY = previousKey;
  }
}
const jpeg = { bytes: new Uint8Array([0xff, 0xd8, 0xff, 0xe0, 1, 2]), mediaType: 'image/jpeg' };

test('Muse structured calls send the schema and photos and keep run provenance', () =>
  withFetch(
    () => ({
      json: {
        id: 'resp_1',
        model: 'muse-spark-1.3',
        status: 'completed',
        output: [
          { type: 'reasoning', content: [] },
          { type: 'message', content: [{ type: 'output_text', text: '{"roomType":"bathroom"}' }] },
        ],
      },
    }),
    async (calls) => {
      const schema = { type: 'object', properties: {}, additionalProperties: false };
      const out = await museJson({ prompt: 'Read this room.', schema, images: [jpeg] });
      assert.deepEqual(out, {
        result: { roomType: 'bathroom' },
        runId: 'resp_1',
        model: 'muse-spark-1.3',
      });
      const [call] = calls;
      assert.equal(call!.url, 'https://api.meta.ai/v1/responses');
      assert.equal(call!.auth, `Bearer ${key}`);
      assert.deepEqual(call!.body.text, {
        format: { type: 'json_schema', name: 'result', schema, strict: true },
      });
      const content = (
        call!.body.input as { content: { type: string; image_url?: string }[] }[]
      )[0]!.content;
      assert.equal(content[0]!.type, 'input_text');
      assert.match(content[1]!.image_url!, /^data:image\/jpeg;base64,/);
    },
  ));

test('Meta API failures never echo the key, and job budgets still apply', () =>
  withFetch(
    () => ({ status: 401, json: { error: { message: `bad key ${key}` } } }),
    async () => {
      await assert.rejects(
        museJson({ prompt: 'x', schema: {} }),
        (error: Error) => error.message.includes('401') && !error.message.includes(key),
      );
      await assert.rejects(
        withMuseBudget(new AbortController().signal, 0, () =>
          museJson({ prompt: 'x', schema: {} }),
        ),
        /budget exhausted/,
      );
    },
  ));

test('Muse Image edits return the generated bytes; SAM returns its raw text', () =>
  withFetch(
    (url) =>
      url.endsWith('/images/edits')
        ? { json: { data: [{ b64_json: Buffer.from('RIFFxxxxWEBP').toString('base64') }] } }
        : {
            json: {
              id: 'resp_sam',
              model: 'sam-3.1',
              status: 'completed',
              output: [{ type: 'message', content: [{ type: 'output_text', text: '<0f>' }] }],
            },
          },
    async (calls) => {
      const edit = await museEditImage({ image: jpeg, prompt: 'Paint the walls sage.' });
      assert.equal(Buffer.from(edit.bytes).toString(), 'RIFFxxxxWEBP');
      assert.equal(calls[0]!.body.model, 'muse-image-1.0');
      const sam = await samSegmentText({ image: jpeg, phrase: 'floor' });
      assert.deepEqual(sam, { text: '<0f>', runId: 'resp_sam', model: 'sam-3.1' });
      assert.equal(calls[1]!.body.model, 'sam-3.1');
    },
  ));
