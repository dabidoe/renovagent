// Turn the curated digest (.local/codes/digest.json, written by a reviewing
// agent from the public-domain 2012 model codes) into committed core data.
// Every excerpt is re-checked here as an exact substring of its section text;
// anything that does not match is dropped, so nothing paraphrased or invented
// can pass as code text.
//
//   node scripts/build-code-digest.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const sections = JSON.parse(readFileSync('.local/codes/sections.json', 'utf8'));
const digest = JSON.parse(readFileSync('.local/codes/digest.json', 'utf8'));
const byKey = new Map(sections.map((s) => [`${s.code}:${s.id}`, s]));
const KINDS = new Set([
  'permit',
  'clearance',
  'ventilation',
  'electrical',
  'plumbing',
  'finish',
  'safety',
  'scope',
]);
const kept = [];
const dropped = [];
for (const d of digest) {
  const s = byKey.get(`${d.code}:${d.id}`);
  const ok =
    s &&
    d.edition === '2012' &&
    typeof d.excerpt === 'string' &&
    d.excerpt.length >= 10 &&
    d.excerpt.length <= 300 &&
    s.text.includes(d.excerpt) &&
    KINDS.has(d.kind);
  if (!ok) {
    dropped.push(`${d.packageId} ${d.code} ${d.id}`);
    continue;
  }
  kept.push({
    packageId: d.packageId,
    code: d.code,
    edition: d.edition,
    id: d.id,
    title: s.title,
    excerpt: d.excerpt,
    why: d.why,
    kind: d.kind,
    // A check keeps only numbers the excerpt states as written; converted
    // values (6 feet 8 inches as 80 in) are dropped rather than trusted.
    check:
      d.check && typeof d.check.value === 'number' && d.excerpt.includes(String(d.check.value))
        ? d.check
        : null,
  });
}
const header = `// Generated by scripts/build-code-digest.mjs from public-domain 2012 ICC model
// codes (Public.Resource.Org copies on archive.org). Excerpts are verified
// verbatim against the source text; \`why\` and \`check\` are a reviewing agent's
// interpretation. Model-code text, not any jurisdiction's adopted code: newer
// editions may renumber or change values. Do not edit by hand.
`;
writeFileSync(
  'packages/core/src/planning/model-code-digest.ts',
  `${header}export const modelCodeDigest = ${JSON.stringify(kept, null, 2)} as const;\n`,
);
console.log(
  `kept ${kept.length}, dropped ${dropped.length}${dropped.length ? `: ${dropped.join('; ')}` : ''}`,
);
