// Reproducible private-project example from the owner's supplied public listing.
// Preserves the original Muse receipt and checks every downloaded source image.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url);
const read = async (path) => JSON.parse(await readFile(new URL(path, root), 'utf8'));
const research = await read('docs/evidence/muse-hutchinson/photo-results-live.json');
const inventory = (await read('docs/evidence/muse-hutchinson/inventory.json')).inventory;
const photoDir = new URL('public/examples/hutchinson/', root);
await mkdir(photoDir, { recursive: true });
const download = process.argv.includes('--download');
for (const photo of research.photoReview.photos) {
  const file = new URL(`${photo.id}.jpg`, photoDir);
  let bytes;
  try {
    bytes = await readFile(file);
  } catch {
    /* Download only when explicitly requested. */
  }
  if (!bytes && download) {
    const response = await fetch(photo.imageUrl, { signal: AbortSignal.timeout(30000) });
    if (!response.ok) throw Error(`${photo.id}: HTTP ${response.status}`);
    bytes = Buffer.from(await response.arrayBuffer());
    await writeFile(file, bytes);
  }
  if (bytes && createHash('sha256').update(bytes).digest('hex') !== photo.sha256)
    throw Error(
      `${photo.id}: changed image; keep the original receipt and review new pixels separately`,
    );
  if (download) console.log(`${photo.id}: ${bytes.length} bytes, original hash verified`);
}
// Source records stay untouched in docs/evidence. Public output always uses the privacy alias.
const privacy = await read('public/examples/hutchinson/source-provenance.json');
const sourceNotes =
  'https://renovagent-production.up.railway.app/examples/hutchinson/source-provenance.json';
if (!privacy.privacyNote || privacy.address === research.address)
  throw Error('A privacy alias and disclosure are required before publishing this example.');
const corpus = {
  address: privacy.address,
  reviewedAt: research.photoReview.reviewedAt,
  manifestHash: research.photoReview.manifestHash,
  batches: research.photoReview.batches,
  originalGoal: research.photoReview.goal,
  originalPlanning: research.photoReview.planning,
  photos: research.photoReview.photos.map((photo) => ({ ...photo, pageUrl: sourceNotes })),
  inventory,
  sources: research.sources.map((source) => ({
    ...source,
    title: source.title.replace(/PAPH\d+/g, 'property identifier withheld'),
    url: sourceNotes,
  })),
  findings: research.findings,
  suppliedListing: sourceNotes,
  suppliedVideo: '',
  visualReceipts: {},
};
for (const [name, file] of [
  ['sam', 'sam-floor.json'],
  ['blender', 'blender-reference.json'],
  ['muse', 'muse-concept.json'],
]) {
  try {
    corpus.visualReceipts[name] = JSON.parse(await readFile(new URL(file, photoDir), 'utf8'));
  } catch {
    /* A capture may be prepared separately. */
  }
}
const out = new URL('apps/web/src/features/house-example/', root);
await mkdir(out, { recursive: true });
await writeFile(
  new URL('hutchinson-corpus.ts', out),
  `// Generated by scripts/prepare-hutchinson-example.mjs. Historical source evidence, not a new model run. Address and property links sanitized for public display; original identifying records omitted from the site bundle.\nimport type { HouseCorpus } from './house-example-model.js';\nexport const hutchinsonCorpus: HouseCorpus = ${JSON.stringify(corpus, null, 2)};\n`,
);
await writeFile(
  new URL('source-provenance.json', photoDir),
  JSON.stringify(
    {
      address: privacy.address,
      privacyNote: privacy.privacyNote,
      sourceReview: 'docs/evidence/muse-hutchinson/photo-results-live.json',
      originalReviewedAt: corpus.reviewedAt,
      images: research.photoReview.photos.map((p) => ({
        id: p.id,
        sha256: p.sha256,
      })),
    },
    null,
    2,
  ),
);
