// Turn the curated adopted-code digest (.local/codes/adopted-digest.json, picked
// by a reviewing agent from enacted California, New York City / New York State
// and Austin code text) into committed core data. Each excerpt is re-checked as
// an exact substring of its section text, or of the whitespace-collapsed raw
// file when the section heading did not parse; failures are dropped.
//
//   node scripts/build-adopted-digest.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const sections = JSON.parse(readFileSync('.local/codes/adopted-sections.json', 'utf8'));
const digest = JSON.parse(readFileSync('.local/codes/adopted-digest.json', 'utf8'));
const key = (x) => `${x.jurisdiction}|${x.code}|${x.edition ?? ''}|${x.id}`;
const byKey = new Map(sections.map((s) => [key(s), s]));
const raw = new Map();
const rawText = (path) => {
  if (!raw.has(path))
    raw.set(path, existsSync(path) ? readFileSync(path, 'utf8').replace(/\s+/g, ' ') : '');
  return raw.get(path);
};
const KINDS = new Set([
  'permit',
  'clearance',
  'ventilation',
  'electrical',
  'plumbing',
  'finish',
  'safety',
  'scope',
]);
const MARKETS = new Set(['bay-area', 'nyc', 'austin']);
const kept = [];
const dropped = [];
for (const d of digest) {
  const s = byKey.get(key(d));
  const found =
    typeof d.excerpt === 'string' &&
    d.excerpt.length >= 10 &&
    d.excerpt.length <= 300 &&
    ((s && s.text.includes(d.excerpt)) ||
      (d.rawFile?.startsWith('.local/codes/') && rawText(d.rawFile).includes(d.excerpt)));
  if (!found || !KINDS.has(d.kind) || !MARKETS.has(d.market) || !d.source?.startsWith('http')) {
    dropped.push(`${d.market} ${d.code} ${d.id}`);
    continue;
  }
  kept.push({
    market: d.market,
    jurisdiction: d.jurisdiction,
    code: d.code,
    edition: d.edition ?? null,
    id: d.id,
    title: s?.title ?? d.title,
    source: d.source,
    packageId: d.packageId,
    excerpt: d.excerpt,
    why: d.why,
    kind: d.kind,
    check:
      d.check && typeof d.check.value === 'number' && d.excerpt.includes(String(d.check.value))
        ? d.check
        : null,
  });
}
const header = `// Generated by scripts/build-adopted-digest.mjs from building codes adopted
// into law for Renovagent's markets: California 2025 Title 24 (Public.Resource.Org),
// New York City 2022 Construction Codes (NYC Department of Buildings), New York
// State 2025 Uniform Code (Public.Resource.Org) and City of Austin amendments to
// the 2024 codes (City of Austin). Excerpts are verified verbatim against the
// source text; \`why\` and \`check\` are a reviewing agent's interpretation.
// Do not edit by hand.
`;
writeFileSync(
  'packages/core/src/planning/adopted-code-digest.ts',
  `${header}export const adoptedCodeDigest = ${JSON.stringify(kept, null, 2)} as const;\n`,
);
const counts = Object.groupBy(kept, (k) => k.market);
console.log(
  `kept ${kept.length} (${Object.entries(counts)
    .map(([m, v]) => `${m} ${v.length}`)
    .join(
      ', ',
    )}), dropped ${dropped.length}${dropped.length ? `: ${dropped.slice(0, 20).join('; ')}` : ''}`,
);
