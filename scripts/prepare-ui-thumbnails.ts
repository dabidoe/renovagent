// Offline derivatives of committed assets, never new provider calls or source downloads.
// Requires the existing local `agent-media` CLI. Originals remain unchanged.
// Run: node --import tsx scripts/prepare-ui-thumbnails.ts
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, mkdir, stat, writeFile } from 'node:fs/promises';
import { HUTCHINSON } from '../apps/web/src/features/house-example/hutchinson-project.js';
import { STUDIO_DIRECTIONS } from '../apps/web/src/features/house-example/studio-directions.js';
import { FLOOR_STYLES } from '../apps/web/src/features/house-example/paint-floor.js';
const sources = new Map<string, number>();
const add = (src: string, edge: number) => {
  const path = src.replace(/^\.\//, '');
  if (!/^(examples|finishes)\/[a-zA-Z0-9./-]+\.jpg$/.test(path) || path.includes('..'))
    throw Error('Expected a bundled photo');
  sources.set(path, Math.max(edge, sources.get(path) ?? 0));
};
for (const room of HUTCHINSON.rooms) add(room.photo.src, 320);
for (const id of ['oakland', 'brooklyn']) {
  const project = JSON.parse(await readFile(`public/examples/${id}/project.json`, 'utf8'));
  for (const room of project.rooms) add(room.photo.src, 320);
}
const gallery = await readFile('apps/web/src/features/house-example/listing-studio.tsx', 'utf8');
for (const match of gallery.matchAll(/cover: '([^']+)'/g)) add(match[1]!, 640);
for (const direction of STUDIO_DIRECTIONS) add(direction.image, 240);
for (const style of FLOOR_STYLES) add(`finishes/${style.id}.jpg`, 192);
await mkdir('public/ui-thumbnails', { recursive: true });
const manifest: Record<string, string> = {};
let originals = 0,
  thumbnails = 0;
for (const [src, edge] of [...sources].sort(([a], [b]) => a.localeCompare(b))) {
  const input = await readFile(`public/${src}`);
  const hash = createHash('sha256')
    .update(input)
    .update(`webp:${edge}:quality75:v1`)
    .digest('hex')
    .slice(0, 16);
  const target = `ui-thumbnails/${hash}.webp`;
  if (!(await stat(`public/${target}`).catch(() => null))) {
    execFileSync(
      'agent-media',
      [
        'optimize-web',
        `public/${src}`,
        '--format',
        'webp',
        '--max-size',
        String(edge),
        '--quality',
        '75',
        '--out',
        `public/${target}`,
      ],
      { stdio: 'pipe' },
    );
  }
  manifest[src] = `./${target}`;
  originals += input.length;
  thumbnails += (await stat(`public/${target}`)).size;
}
await writeFile(
  'apps/web/src/features/house-example/ui-thumbnails.ts',
  `// Generated by scripts/prepare-ui-thumbnails.ts. UI derivatives only.\nconst thumbnails: Record<string, string> = ${JSON.stringify(manifest, null, 2)};\nexport const thumbnailUrl = (src: string) => {\n  const starter = /^\\.?\\/examples\\/starter-([a-z0-9-]+)\\/source-[a-f0-9]+\\.jpg$/.exec(src)?.[1];\n  return starter ? \`/starter-rooms/\${starter}-thumb.jpg\` : thumbnails[src.replace(/^\\.\\//, '').replace(/^\\//, '')] ?? src;\n};\n`,
);
console.log(
  JSON.stringify({ count: sources.size, originalBytes: originals, thumbnailBytes: thumbnails }),
);
