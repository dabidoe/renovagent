import { createHash } from 'node:crypto';
import { DomainError, type Command, type CommandResult } from '@renovagent/contracts';
import { handleCommand } from '@renovagent/core';
import { MongoWorkspaceRepository } from './repository.js';

export type StartAgentProject = {
  requestId: string;
  name: string;
  brief: string;
  propertyId?: string;
};

// Intent-level application service shared by transports. A relayed request is
// saved as a proposal, never promoted into measured or verified source facts.
export async function startAgentProject(
  repository: MongoWorkspaceRepository,
  input: StartAgentProject,
) {
  const key = createHash('sha256').update(input.requestId).digest('hex').slice(0, 24);
  const projectId = `agent-project:${key}`;
  const propertyId = input.propertyId ?? `agent-home:${key}`;
  const artifactId = `${projectId}:agent-brief`;
  const createId = `mcp-start:${key}:create`;
  return repository.update((doc) => {
    const state = doc.workspace;
    const property = state.properties[propertyId];
    if (input.propertyId && !property)
      throw new DomainError(
        'NOT_FOUND',
        'Choose a home returned by list_homes, or omit propertyId',
      );
    const prior = state.commands[createId];
    const propertyRevision = prior ? prior.result.propertyRevision - 1 : (property?.revision ?? 0);
    const create: Command = {
      commandId: createId,
      projectId,
      baseRevision: 0,
      basePropertyRevision: propertyRevision,
      type: 'CreateProject',
      payload: {
        propertyId,
        name: input.name,
        ...(!input.propertyId ? { newProperty: { name: 'My home' } } : {}),
        spaces: [],
      },
    };
    const context = { ownerId: repository.ownerId, now: new Date().toISOString() };
    const created = handleCommand(state, create, context);
    const proposal: Command = {
      commandId: `mcp-start:${key}:brief`,
      projectId,
      baseRevision: created.result.projectRevision,
      basePropertyRevision: created.result.propertyRevision,
      type: 'ProposeArtifact',
      payload: {
        artifactId,
        supersedesRevision: 0,
        inputRefs: [],
        evidenceIds: [],
        content: {
          kind: 'project-brief',
          sections: [
            { title: 'Request relayed by your agent', text: input.brief },
            {
              title: 'Working draft',
              text: 'Saved project intent. Photos, measurements, specifications, costs and requirements remain to be investigated. No physical facts or technical approvals were inferred.',
            },
          ],
        },
      },
    };
    const proposed = handleCommand(created.state, proposal, context);
    doc.workspace = proposed.state;
    const results: CommandResult[] = [created.result, proposed.result];
    return {
      projectId,
      propertyId,
      artifactRef: { kind: 'artifact' as const, id: artifactId, revision: 1 },
      results,
      note: 'Project and proposed brief saved. Continue developing options and material requirements from evidence; no estimate or design has been generated by this tool.',
    };
  });
}
