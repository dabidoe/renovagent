import { workspaceRequest, type SessionInfo } from '../../adapters/http/project-repository.js';
import type { RoomModel } from '@renovagent/core';
import type { RoomLook } from './room-scene.js';

// "Photoreal" for the 3D view: an eye-level still of the measured model goes
// to Muse Image (POST /model/photoreal), which renders it as a photo of the
// same room in the chosen finishes. Runs from any phone; the result is a
// generated preview, labelled as such and not saved to the project.
//
// "Blender HD" (when the server has the Modal render service) renders the
// same measured model with Cycles on a cloud GPU: an eye-level interior, a
// dollhouse view, a plan and the room as GLB, all offered for download.

export function attachPhotoreal(
  host: HTMLElement,
  capture: () => Promise<Blob>,
  look: () => RoomLook,
  model: RoomModel,
) {
  const bar = document.createElement('div');
  bar.className = 'room3d-photoreal';
  const run = document.createElement('button');
  run.type = 'button';
  run.className = 'room3d-muse';
  run.textContent = '✦ Photoreal';
  run.title = 'Render this measured room as a photo with Muse Image';
  const switcher = document.createElement('div');
  switcher.className = 'room3d-photoreal-switch';
  switcher.setAttribute('role', 'group');
  switcher.setAttribute('aria-label', '3D or photoreal');
  switcher.hidden = true;
  const as3d = document.createElement('button');
  as3d.type = 'button';
  as3d.textContent = '3D';
  const asPhoto = document.createElement('button');
  asPhoto.type = 'button';
  asPhoto.textContent = 'Photoreal';
  switcher.append(as3d, asPhoto);
  const status = document.createElement('span');
  status.className = 'room3d-photoreal-status';
  status.setAttribute('role', 'status');
  const hd = document.createElement('button');
  hd.type = 'button';
  hd.className = 'room3d-muse';
  hd.textContent = 'Blender HD';
  hd.title = 'Render this measured room in Blender on a cloud GPU';
  hd.hidden = true;
  const asBlender = document.createElement('button');
  asBlender.type = 'button';
  asBlender.textContent = 'Blender';
  asBlender.hidden = true;
  switcher.append(asBlender);
  const downloads = document.createElement('div');
  downloads.className = 'room3d-photoreal-downloads';
  downloads.hidden = true;
  bar.append(run, hd, switcher, status);

  const figure = document.createElement('figure');
  figure.className = 'room3d-photoreal-view';
  figure.hidden = true;
  const image = document.createElement('img');
  const caption = document.createElement('figcaption');
  figure.append(image, caption);
  host.append(figure, bar, downloads);
  void (workspaceRequest('/session') as Promise<SessionInfo>)
    .then((session) => (hd.hidden = !session.render))
    .catch(() => {});

  let url = '';
  let photoCaption = '';
  let blender: { url: string; caption: string; files: string[] } | null = null;
  const show = (view: '3d' | 'photo' | 'blender') => {
    figure.hidden = view === '3d';
    host.classList.toggle('is-photoreal', view !== '3d');
    if (view === 'photo') {
      image.src = url;
      caption.textContent = photoCaption;
    }
    if (view === 'blender' && blender) {
      image.src = blender.url;
      caption.textContent = blender.caption;
    }
    downloads.hidden = view !== 'blender';
    as3d.setAttribute('aria-pressed', String(view === '3d'));
    asPhoto.setAttribute('aria-pressed', String(view === 'photo'));
    asBlender.setAttribute('aria-pressed', String(view === 'blender'));
  };
  as3d.addEventListener('click', () => show('3d'));
  asPhoto.addEventListener('click', () => show('photo'));
  asBlender.addEventListener('click', () => show('blender'));
  const asBase64 = async (blob: Blob) => {
    let binary = '';
    for (const n of new Uint8Array(await blob.arrayBuffer())) binary += String.fromCharCode(n);
    return btoa(binary);
  };
  const fromBase64 = (data: string, type: string) =>
    new Blob([Uint8Array.from(atob(data), (c) => c.charCodeAt(0))], { type });
  const failed = (e: unknown) => {
    const text = e instanceof Error ? e.message : String(e);
    status.textContent = /unavailable|Failed to fetch/i.test(text)
      ? 'This needs the Renovagent server (npm run dev:connected).'
      : text.slice(0, 160);
  };
  // Muse Image from a still: the 3D capture, or the Blender interior.
  const photoreal = async (still: Blob, source: string) => {
    const current = look();
    const result = (await workspaceRequest('/model/photoreal', {
      image: await asBase64(still),
      wall: current.wallColor,
      floor: current.floorFinish,
    })) as { image: string; mediaType: string; model: string; note: string };
    if (url) URL.revokeObjectURL(url);
    url = URL.createObjectURL(fromBase64(result.image, result.mediaType));
    image.alt = `Generated photoreal preview: ${current.wallColor} walls, ${current.floorFinish} floor`;
    photoCaption = `Generated by ${result.model} from ${source} (${current.wallColor} walls, ${current.floorFinish}). ${result.note}`;
    switcher.hidden = false;
    show('photo');
  };
  run.addEventListener('click', async () => {
    run.disabled = true;
    run.textContent = 'Muse Image is rendering…';
    status.textContent = '';
    try {
      await photoreal(await capture(), 'the measured 3D model');
    } catch (e) {
      failed(e);
    } finally {
      run.disabled = false;
      run.textContent = '✦ Photoreal';
    }
  });
  hd.addEventListener('click', async () => {
    hd.disabled = true;
    status.textContent = '';
    const started = Date.now();
    const tick = setInterval(
      () =>
        (hd.textContent = `Blender on a cloud GPU… ${Math.round((Date.now() - started) / 1000)} s`),
      1000,
    );
    try {
      const current = look();
      const { id } = (await workspaceRequest('/model/hq-render', {
        model,
        wall: current.wallColor,
        floor: current.floorFinish,
      })) as { id: string };
      let result: Record<string, string> = { status: 'running' };
      while (result.status === 'running') {
        if (Date.now() - started > 10 * 60 * 1000) throw Error('The render took too long');
        await new Promise((r) => setTimeout(r, 4000));
        result = (await workspaceRequest(`/model/hq-render/${encodeURIComponent(id)}`)) as Record<
          string,
          string
        >;
      }
      if (result.status !== 'done') throw Error(result.error || 'The render failed');
      for (const old of blender?.files ?? []) URL.revokeObjectURL(old);
      const files = {
        interior: URL.createObjectURL(fromBase64(result.interior!, 'image/png')),
        perspective: URL.createObjectURL(fromBase64(result.perspective!, 'image/png')),
        plan: URL.createObjectURL(fromBase64(result.plan!, 'image/png')),
        glb: URL.createObjectURL(fromBase64(result.glb!, 'model/gltf-binary')),
      };
      const seconds = Math.round((Date.now() - started) / 1000);
      blender = {
        url: files.interior,
        caption: `Rendered in Blender ${result.blender} (Cycles, ${result.device}) on a cloud GPU in ${seconds} s, from the measured model: ${current.wallColor} walls, ${current.floorFinish}. A rendering, not a photo.`,
        files: Object.values(files),
      };
      downloads.replaceChildren(
        ...(
          [
            [files.interior, 'Interior (PNG)', 'room-interior.png'],
            [files.perspective, 'Dollhouse (PNG)', 'room-dollhouse.png'],
            [files.plan, 'Plan (PNG)', 'room-plan.png'],
            [files.glb, '3D model (.glb)', 'room.glb'],
          ] as const
        ).map(([href, label, name]) => {
          const a = document.createElement('a');
          a.href = href;
          a.download = name;
          a.textContent = label;
          return a;
        }),
      );
      const finish = document.createElement('button');
      finish.type = 'button';
      finish.className = 'room3d-muse';
      finish.textContent = '✦ Finish with Muse Image';
      finish.addEventListener('click', async () => {
        finish.disabled = true;
        finish.textContent = 'Muse Image is rendering…';
        try {
          await photoreal(await (await fetch(files.interior)).blob(), 'the Blender render');
        } catch (e) {
          failed(e);
        } finally {
          finish.disabled = false;
          finish.textContent = '✦ Finish with Muse Image';
        }
      });
      downloads.append(finish);
      switcher.hidden = false;
      asBlender.hidden = false;
      show('blender');
    } catch (e) {
      failed(e);
    } finally {
      clearInterval(tick);
      hd.disabled = false;
      hd.textContent = 'Blender HD';
    }
  });
  return {
    dispose() {
      if (url) URL.revokeObjectURL(url);
      for (const old of blender?.files ?? []) URL.revokeObjectURL(old);
      downloads.remove();
      host.classList.remove('is-photoreal');
      bar.remove();
      figure.remove();
    },
  };
}
