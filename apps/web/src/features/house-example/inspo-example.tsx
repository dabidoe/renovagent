import { useEffect, useState } from 'react';
import { InspiredView } from './inspo-panel.js';
import { shopLinks } from './shop-links.js';

// A worked run of the Inspiration panel, saved from the real models
// (public/examples/bedroom-refresh). The inspiration pin itself is not shipped.
type Example = {
  title: string;
  made: string;
  source: string;
  items: { name: string; kind: string; colour: string }[];
  walls: { read: string; matches: { name: string; code: string; hex: string; deltaE: number }[] };
  changes: { target: string; becomes: string }[];
  models: { items: string; outlines: string; restyle: string };
};
const DIR = './examples/bedroom-refresh';

export function InspoExample({ onBack, onTry }: { onBack: () => void; onTry: () => void }) {
  const [example, setExample] = useState<Example | null>(null);
  const [error, setError] = useState('');
  useEffect(() => {
    fetch(`${DIR}/example.json`)
      .then((r) => (r.ok ? (r.json() as Promise<Example>) : Promise.reject(Error(r.statusText))))
      .then(setExample, (e: Error) => setError(e.message));
  }, []);
  if (error) return <p className="pf-intake-error">This example did not load: {error}</p>;
  if (!example) return <p className="pf-sub">Loading the example…</p>;
  return (
    <section className="pf-inspo-example" aria-label={example.title}>
      <button type="button" className="pf-reset" onClick={onBack}>
        All examples
      </button>
      <p className="pf-kicker">Worked example · made with the Inspiration panel</p>
      <h1>{example.title}</h1>
      <p className="pf-sub">{example.source}</p>
      <InspiredView
        before={`${DIR}/before.jpg`}
        after={`${DIR}/after.jpg`}
        caption={`Generated by ${example.models.restyle} from the bedroom photo and the pin; a picture, not a plan.`}
      />
      <div className="pf-inspo-example-grid">
        <div>
          <h3>What made the look</h3>
          <p className="pf-inspo-note">
            {example.models.items} named them, {example.models.outlines} outlined each one, and the
            colour is read from inside its outline.
          </p>
          <ul className="pf-inspo-items">
            {example.items.map((item) => (
              <li key={item.name}>
                <label>
                  <i style={{ background: item.colour }} />
                  <span>
                    {item.name}
                    <small>{item.kind}</small>
                  </span>
                </label>
                {item.kind !== 'walls' && (
                  <p className="pf-inspo-shop">
                    {shopLinks(item.name).map((l) => (
                      <a key={l.store} href={l.href} target="_blank" rel="noreferrer">
                        {l.store}
                      </a>
                    ))}
                  </p>
                )}
              </li>
            ))}
          </ul>
        </div>
        <div>
          <h3>Closest paints to the walls</h3>
          <p className="pf-inspo-note">
            Read as {example.walls.read} from the photo, lighting included; the closest catalog
            colours, not the paint on that wall.
          </p>
          <ul className="pf-inspo-example-paints">
            {example.walls.matches.map((m) => (
              <li key={m.code}>
                <i style={{ background: m.hex }} />
                <span>
                  {m.name} <small>{m.code}</small>
                </span>
                <small>ΔE {m.deltaE}</small>
              </li>
            ))}
          </ul>
          <div className="pf-inspo-changes">
            <h4>What Muse changed in the room</h4>
            <ul>
              {example.changes.map((c) => (
                <li key={c.target}>
                  <s>{c.target}</s> → {c.becomes}
                </li>
              ))}
            </ul>
          </div>
          <p className="pf-inspo-note">Store links are searches, not picked products.</p>
          <button type="button" className="pf-inspo-go" onClick={onTry}>
            Try it with your room
          </button>
        </div>
      </div>
    </section>
  );
}
